package com.org;

public class Flat {
    private int flatId;
    private String unitNo, flatType, tower, status, reraNo;
    private int floor;
    private double agreementValue;
    private String possessionDate;

    public int getFlatId() { return flatId; }
    public void setFlatId(int flatId) { this.flatId = flatId; }
    public String getUnitNo() { return unitNo; }
    public void setUnitNo(String unitNo) { this.unitNo = unitNo; }
    public String getFlatType() { return flatType; }
    public void setFlatType(String flatType) { this.flatType = flatType; }
    public String getTower() { return tower; }
    public void setTower(String tower) { this.tower = tower; }
    public int getFloor() { return floor; }
    public void setFloor(int floor) { this.floor = floor; }
    public double getAgreementValue() { return agreementValue; }
    public void setAgreementValue(double agreementValue) { this.agreementValue = agreementValue; }
    public String getStatus() { return status; }
    public void setStatus(String status) { this.status = status; }
    public String getPossessionDate() { return possessionDate; }
    public void setPossessionDate(String possessionDate) { this.possessionDate = possessionDate; }
    public String getReraNo() { return reraNo; }
    public void setReraNo(String reraNo) { this.reraNo = reraNo; }
}